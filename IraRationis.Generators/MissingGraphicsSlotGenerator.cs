using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace IraRationis.Generators;

[Generator]
public sealed class MissingGraphicsSlotGenerator : IIncrementalGenerator
{
    private const int SlotCount = 160;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output =>
        {
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using System.Runtime.CompilerServices;");
            source.AppendLine("using System.Runtime.InteropServices;");
            source.AppendLine("namespace IraRationis.Graphics;");
            source.AppendLine("public static unsafe partial class ConsoleGraphicsDevice");
            source.AppendLine("{");
            source.AppendLine("    private static readonly nint[] MissingAddresses =");
            source.AppendLine("    [");
            for (var index = 0; index < SlotCount; index++)
            {
                source.AppendLine($"        (nint)(delegate* unmanaged[Stdcall]<nint, nint, void>)&Missing{index},");
            }

            source.AppendLine("    ];");
            source.AppendLine("    private static nint MissingAddress(int index)");
            source.AppendLine("    {");
            source.AppendLine("        return MissingAddresses[index];");
            source.AppendLine("    }");
            for (var index = 0; index < SlotCount; index++)
            {
                source.AppendLine("    [UnmanagedCallersOnly(CallConvs = [typeof(CallConvStdcall)])]");
                source.AppendLine($"    private static void Missing{index}(nint first, nint second)");
                source.AppendLine("    {");
                source.AppendLine($"        Trap({index}, first, second);");
                source.AppendLine("    }");
            }

            source.AppendLine("}");
            output.AddSource("ConsoleGraphicsDevice.Missing.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        });
    }
}
